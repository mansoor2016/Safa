            (109, 30), (110, 30), (111, 30), (112, 30), (113, 30), (114, 30),
        ]

        // Find the juz for this surah by finding the highest surah number <= self
        for i in stride(from: juzStarts.count - 1, through: 0, by: -1) {
            if self >= juzStarts[i].surah {
                return juzStarts[i].juz
            }
        }
        return 1 // Default to juz 1 if surah is < 1
    }
}


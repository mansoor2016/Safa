extension Int {
    /// Returns the juz number (1-30) for a given surah number (1-114)
    /// Uses accurate mapping based on standard Quran juz boundaries
    var juzNumber: Int {
        let juzStarts: [(surah: Int, juz: Int)] = [
            (1, 1), (2, 1), (3, 3), (4, 4), (5, 6), (6, 7), (7, 8),

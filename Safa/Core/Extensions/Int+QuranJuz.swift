            (26, 26), (27, 27), (28, 28), (29, 28), (30, 29), (31, 29),
            (32, 30), (33, 30), (34, 30), (35, 30), (36, 30),
            // 37-114 all in juz 30
            (37, 30), (38, 30), (39, 30), (40, 30), (41, 30), (42, 30),
            (43, 30), (44, 30), (45, 30), (46, 30), (47, 30), (48, 30),
            (49, 30), (50, 30), (51, 30), (52, 30), (53, 30), (54, 30),
            (55, 30), (56, 30), (57, 30), (58, 30), (59, 30), (60, 30),
            (61, 30), (62, 30), (63, 30), (64, 30), (65, 30), (66, 30),
            (67, 30), (68, 30), (69, 30), (70, 30), (71, 30), (72, 30),
